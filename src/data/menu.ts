export function getCrustPriceForSize(crustId: CrustOptionId, size: PizzaSize): number {
  const found = CRUST_OPTIONS.find((c) => c.id === crustId);
  return found ? found.prices[size] : 0;
}

export function getPizzaPriceForSize(item: MenuItem, size: PizzaSize): number {
  switch (size) {
    case 'pequena':
      return item.priceSmall ?? item.priceMedium;
    case 'media':
      return item.priceMedium;
    case 'grande':
      return item.priceLarge ?? item.priceMedium;
    case 'gigante':
      return item.priceGiant ?? item.priceLarge ?? item.priceMedium;
  }
}

export function createWhatsAppUrl(customMessage: string): string {
  const encoded = encodeURIComponent(customMessage);
  return `https://wa.me/${WHATSAPP_NUMBER}?text=${encoded}`;
}

